#!/usr/bin/env python3
"""Rebuild the embedded reference from the public v4 literal and REG0.canon.

Runtime gates do not call this. It checks that the public AUTHREF literal and
the exported REG0.canon are the same 706 entries, then writes embed_data.py
and reggate.pmp.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
V4 = Path("/tmp/v4src/judge/judge-v4.pmp")
CANON = Path("/workspace/reg0-gate/REG0.canon")
TPL = ROOT / "reggate.pmp.tpl"
PIN = "d3dbc73283b61a2ba72431552d33c1810e140e24bbfda85b1a30aef006dac047"


def payload_from_v4():
    line = V4.read_text(encoding="latin1").splitlines()[45]
    prefix = 'text AUTHREF "'
    if not line.startswith(prefix) or not line.endswith('"'):
        raise SystemExit("v4 AUTHREF line has moved")
    payload = line[len(prefix):-1]
    digest = hashlib.sha256(payload.encode("ascii")).hexdigest()
    if digest != PIN:
        raise SystemExit(f"AUTHREF sha changed: {digest}")
    if any(c in payload for c in '"\\\n'):
        raise SystemExit("AUTHREF is not a plain pmp literal")
    return payload


def canon_entries(text):
    toks = text.split()
    pos = 0

    def eat():
        nonlocal pos
        t = toks[pos]
        pos += 1
        return t

    def form():
        c = eat()
        out = [c]
        if c in {"e", "q"}:
            out += [eat(), eat()]
        elif c == "p":
            out.append(eat())
            n = int(eat())
            out.append(str(n))
            for _ in range(n):
                out.append(eat())
        elif c in {"n", "a", "x"}:
            out += form()
        elif c in {"i", "k", "d", "b"}:
            out += form()
            out += form()
        else:
            raise SystemExit(f"bad tag {c}")
        return out

    if eat() != "REG0V1" or int(eat()) != 706:
        raise SystemExit("canon header")
    entries = []
    for _ in range(706):
        if eat() != "F":
            raise SystemExit("F")
        formula = form()
        if eat() != "H":
            raise SystemExit("H")
        hc = int(eat())
        hyps = [eat() for _ in range(hc)]
        entries.append(formula + [str(hc)] + hyps)
    if pos != len(toks):
        raise SystemExit("canon tail")
    return entries


def norm(tokens):
    out = []
    for t in tokens:
        out.append(int(t) if t.isdigit() else t)
    return out


def main():
    payload = payload_from_v4()
    v4_entries = []
    cur = []
    for t in payload.split():
        if t == "!":
            v4_entries.append(cur)
            cur = []
        else:
            cur.append(t)
    if cur or len(v4_entries) != 706:
        raise SystemExit("v4 entry split")
    canon = canon_entries(CANON.read_text(encoding="ascii"))
    for i, (a, b) in enumerate(zip(canon, v4_entries)):
        if norm(a) != norm(b):
            raise SystemExit(f"canon/v4 differ at {i}")
    embed = (
        "# Generated by build.py. Do not load REG0.canon from here.\n"
        "# AUTHREF bytes are judge-v4.pmp's embedded literal at\n"
        "# 63f45bbcaa88e370827d2dd2e95a6d422fb8c589.\n"
        f"AUTHREF_SHA256 = {json.dumps(PIN)}\n"
        f"AUTHREF = {json.dumps(payload)}\n"
        "\n"
        "def _entries(payload):\n"
        "    entries = []\n"
        "    cur = []\n"
        "    for tok in payload.split():\n"
        "        if tok == '!':\n"
        "            entries.append(tuple(int(t) if t.isdigit() else t for t in cur))\n"
        "            cur = []\n"
        "        else:\n"
        "            cur.append(tok)\n"
        "    if cur or len(entries) != 706:\n"
        "        raise SystemExit('embed split')\n"
        "    return tuple(entries)\n"
        "\n"
        "ENTRIES = _entries(AUTHREF)\n"
    )
    (ROOT / "embed_data.py").write_text(embed, encoding="ascii", newline="\n")
    tpl = TPL.read_text(encoding="ascii")
    if tpl.count("@@AUTHREF@@") != 1:
        raise SystemExit("template")
    (ROOT / "reggate.pmp").write_text(tpl.replace("@@AUTHREF@@", payload), encoding="ascii", newline="\n")
    # The generated pmp literal must be the public literal, byte for byte.
    line = (ROOT / "reggate.pmp").read_text(encoding="ascii").splitlines()[15]
    # line index is not stable if the header changes; search instead.
    found = [ln[len('text AUTHREF "'):-1] for ln in (ROOT / "reggate.pmp").read_text(encoding="ascii").splitlines() if ln.startswith('text AUTHREF "')]
    if found != [payload]:
        raise SystemExit("pmp literal mismatch")
    print("embed ok", PIN)


if __name__ == "__main__":
    main()
